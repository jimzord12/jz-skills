#!/usr/bin/env node
// generate-readme-index.mjs — regenerate the "Skills index" table in README.md
// from every own skill's frontmatter (name, metadata.version, description), grouped
// by domain. Own skills only; deprecated/ and in-progress/ are skipped.
//
// Run:  node scripts/generate-readme-index.mjs
//
// README.md must contain the marker pair:
//   <!-- SKILLS_INDEX:START -->
//   <!-- SKILLS_INDEX:END -->
// Everything between the markers is replaced.

import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join, dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OWN_DIR = join(repoRoot, 'skills');
const README = join(repoRoot, 'README.md');
const SKIP_DIRS = [join(OWN_DIR, 'deprecated'), join(OWN_DIR, 'in-progress')];
const START = '<!-- SKILLS_INDEX:START -->';
const END = '<!-- SKILLS_INDEX:END -->';

function findSkillDirs(root) {
  const out = [];
  if (!existsSync(root)) return out;
  const walk = (dir) => {
    if (SKIP_DIRS.some((s) => dir === s || dir.startsWith(s + sep))) return;
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    if (entries.some((e) => e.isFile() && e.name === 'SKILL.md')) {
      out.push(dir);
      return;
    }
    for (const e of entries) {
      const full = join(dir, e.name);
      try {
        if (statSync(full).isDirectory()) walk(full);
      } catch {
        /* dangling symlink */
      }
    }
  };
  walk(root);
  return out;
}

function frontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  return m ? m[1] : '';
}

function field(fm, key) {
  const m = fm.match(new RegExp(`^\\s*${key}:\\s*(.+?)\\s*$`, 'm'));
  return m ? m[1].trim() : '';
}

// First sentence/line of the description, whether inline or a block scalar.
function shortDescription(fm) {
  const lines = fm.split('\n');
  const i = lines.findIndex((l) => /^description:/.test(l));
  if (i === -1) return '';
  let raw = lines[i].replace(/^description:\s*/, '').trim();
  if (raw === '|' || raw === '>' || raw === '|-' || raw === '>-') {
    // block scalar — first non-empty indented line
    raw = (lines.slice(i + 1).find((l) => l.trim()) || '').trim();
  }
  const firstSentence = raw.split(/(?<=\.)\s/)[0];
  const trimmed = firstSentence.length > 140 ? firstSentence.slice(0, 137) + '…' : firstSentence;
  return trimmed.replace(/\|/g, '\\|'); // escape pipes for the markdown table
}

const skills = findSkillDirs(OWN_DIR).map((dir) => {
  const text = readFileSync(join(dir, 'SKILL.md'), 'utf8').replace(/\r\n/g, '\n');
  const fm = frontmatter(text);
  const relDir = relative(OWN_DIR, dir).split(sep);
  return {
    name: field(fm, 'name') || relDir[relDir.length - 1],
    version: field(fm, 'version') || '—',
    description: shortDescription(fm),
    domain: relDir[0] || 'misc',
  };
});

// Group by domain, sorted.
const byDomain = new Map();
for (const s of skills.sort((a, b) => a.name.localeCompare(b.name))) {
  if (!byDomain.has(s.domain)) byDomain.set(s.domain, []);
  byDomain.get(s.domain).push(s);
}

const sections = [...byDomain.keys()].sort().map((domain) => {
  const rows = byDomain
    .get(domain)
    .map((s) => `| \`${s.name}\` | ${s.version} | ${s.description} |`)
    .join('\n');
  return `### ${domain}\n\n| Skill | Version | Description |\n| --- | --- | --- |\n${rows}`;
});

const table = `${START}\n_${skills.length} own skills. Generated by \`scripts/generate-readme-index.mjs\` — do not edit by hand._\n\n${sections.join('\n\n')}\n${END}`;

if (!existsSync(README)) {
  console.error(`✖ ${relative(repoRoot, README)} not found. Create it with the marker pair first.`);
  process.exit(1);
}
const readme = readFileSync(README, 'utf8');
if (!readme.includes(START) || !readme.includes(END)) {
  console.error(`✖ README.md is missing the marker pair:\n   ${START}\n   ${END}`);
  process.exit(1);
}

const next = readme.replace(new RegExp(`${START}[\\s\\S]*?${END}`), table);
writeFileSync(README, next);
console.log(`✓ Updated README.md skills index: ${skills.length} skills across ${byDomain.size} domains.`);
